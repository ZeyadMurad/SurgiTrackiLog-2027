export interface CvBuilderViewProps {
  language: Lang;
  profile: UserProfile | null;
  cases: ClinicalCase[];
  trainingRecords: TrainingRecord[];
  skills: UserSkill[];
  supervisors: any[]; // existing Supervisor type
  initialData?: Partial<CvData>;
  onSave?: (data: CvData) => Promise<void>;
}

export const CvBuilderView: React.FC<CvBuilderViewProps> = ({
  language,
  profile,
  cases,
  trainingRecords,
  skills,
  supervisors,
  initialData,
  onSave,
}) => {
  const t = I18N[language];
  const isRtl = language === 'ar';
  const [activeTab, setActiveTab] = useState<'sections' | 'preview'>('sections');
  const [isGenerating, setIsGenerating] = useState(false);
  const [autoGenComplete, setAutoGenComplete] = useState(false);
  const [isExporting, setIsExporting] = useState<'pdf' | 'docx' | null>(null);

  // CV state
  const [cvData, setCvData] = useState<CvData>({
    fullName: profile?.fullName || '',
    title: profile?.currentPosition || '',
    email: profile?.email || '',
    phone: '',
    address: '',
    country: profile?.country || '',
    nationality: '',
    dateOfBirth: '',
    profilePhotoUrl: profile?.profilePhotoUrl,
    professionalSummary: profile?.biography || '',
    education: [],
    experience: [],
    certifications: [],
    publications: [],
    awards: [],
    languages: [],
    memberships: [],
    references: [],
    conferences: [],
    language: language as CvLanguage,
    template: getDefaultTemplateForLanguage(language as CvLanguage),
    colorScheme: 'navy',
    lastGeneratedAt: new Date().toISOString(),
    ...initialData,
  });

  // Re-sync when profile changes
  useEffect(() => {
    if (profile && !initialData) {
      setCvData(prev => ({
        ...prev,
        fullName: prev.fullName || profile.fullName,
        email: prev.email || profile.email,
        title: prev.title || profile.currentPosition,
        country: prev.country || profile.country,
        professionalSummary: prev.professionalSummary || profile.biography,
      }));
    }
  }, [profile]);

  // ----------------------------------------------------------------------------
  // AUTO-GENERATE FROM PORTFOLIO
  // ----------------------------------------------------------------------------

  const handleAutoGenerate = async () => {
    setIsGenerating(true);
    setAutoGenComplete(false);

    // Simulate async analysis (in production, this could call Gemini AI)
    await new Promise(resolve => setTimeout(resolve, 800));

    // 1) Generate professional summary
    const specialty = profile?.specialty || 'General Surgery';
    const yearsExp = trainingRecords.length > 0
      ? Math.max(1, Math.floor(trainingRecords.length / 50) + 1)
      : 1;

    const summaryTemplates: Record<CvLanguage, string> = {
      en: `${profile?.fullName || 'Surgical professional'} is a ${profile?.currentPosition || 'surgical trainee'} in ${specialty} with approximately ${yearsExp} years of clinical experience. Has documented ${cases.length} clinical cases and ${trainingRecords.length} training hours across ${supervisors.length} supervisors. Committed to evidence-based surgical practice, continuing education, and patient-centered care.`,
      ar: `${profile?.fullName || 'جراح'} هو ${profile?.currentPosition || 'متدرب جراحي'} في ${specialty} مع حوالي ${yearsExp} سنوات من الخبرة السريرية. وثّق ${cases.length} حالة سريرية و${trainingRecords.length} ساعة تدريب تحت ${supervisors.length} مشرفين. ملتزم بالممارسة الجراحية المبنية على الأدلة، والتعليم المستمر، ورعاية المريض.`,
      de: `${profile?.fullName || 'Chirurg'} ist ${profile?.currentPosition || 'chirurgischer Auszubildender'} in ${specialty} mit ca. ${yearsExp} Jahren klinischer Erfahrung. Hat ${cases.length} klinische Fälle und ${trainingRecords.length} Trainingsstunden unter ${supervisors.length} Supervisoren dokumentiert.`,
    };

    // 2) Build clinical experience summary
    const proceduresBySpecialty: { specialty: string; count: number }[] = [];
    cases.forEach(c => {
      const existing = proceduresBySpecialty.find(s => s.specialty === c.specialty);
      if (existing) existing.count++;
      else proceduresBySpecialty.push({ specialty: c.specialty, count: 1 });
    });

    const proceduresByRole: { role: string; count: number }[] = [];
    cases.forEach(c => {
      if (c.surgicalProcedure) {
        const existing = proceduresByRole.find(r => r.role === c.surgicalProcedure!.participationRole);
        if (existing) existing.count++;
        else proceduresByRole.push({ role: c.surgicalProcedure.participationRole, count: 1 });
      }
    });

    const topProcedures: { name: string; count: number }[] = [];
    cases.forEach(c => {
      if (c.surgicalProcedure) {
        const existing = topProcedures.find(p => p.name === c.surgicalProcedure!.procedureName);
        if (existing) existing.count++;
        else topProcedures.push({ name: c.surgicalProcedure.procedureName, count: 1 });
      }
    });
    topProcedures.sort((a, b) => b.count - a.count);
    topProcedures.splice(8);

    const totalHours = trainingRecords.reduce((sum, r) => sum + (r.netTrainingHours || 0), 0);
    const verifiedHours = trainingRecords.filter(r => r.verified).reduce((sum, r) => sum + (r.netTrainingHours || 0), 0);
    const totalProcedures = cases.filter(c => c.surgicalProcedure).length;

    // 3) Generate experience entries from supervisors
    const supervisorExp = supervisors.slice(0, 3).map((sup, idx) => ({
      id: `auto-exp-${idx}`,
      position: profile?.currentPosition || 'Trainee Surgeon',
      hospital: sup.hospital,
      startDate: idx === 0 ? '2024-01-01' : idx === 1 ? '2023-01-01' : '2022-01-01',
      endDate: idx === 0 ? 'Present' : '2024-01-01',
      description: `Training under ${sup.fullName} (${sup.academicTitle || ''} ${sup.academicDegree || ''}). Specializing in ${sup.specialty}.`,
      supervisor: sup.fullName,
      location: sup.country,
    }));

    // 4) Skills matrix
    const skillsMatrix = skills.slice(0, 12).map(s => ({
      skillName: s.name,
      exposureLevel: s.exposureLevel,
      competencyStatus: s.competencyStatus,
      totalHours: s.totalDocumentedHours,
    }));

    setCvData(prev => ({
      ...prev,
      professionalSummary: prev.professionalSummary || summaryTemplates[prev.language as CvLanguage],
      experience: prev.experience.length > 0 ? prev.experience : supervisorExp,
      clinicalExperience: {
        totalProcedures,
        verifiedProcedures: cases.filter(c => c.surgicalProcedure && (c as any).verified).length,
        totalHours,
        verifiedHours,
        proceduresBySpecialty,
        proceduresByRole,
        topProcedures,
      },
      skillsMatrix,
      lastGeneratedAt: new Date().toISOString(),
    }));

    setIsGenerating(false);
    setAutoGenComplete(true);
    setTimeout(() => setAutoGenComplete(false), 4000);
  };

  // ----------------------------------------------------------------------------
  // EXPORT
  // ----------------------------------------------------------------------------

  const handleExportPdf = async () => {
    setIsExporting('pdf');
    try {
      const template = CV_TEMPLATES.find(t => t.id === cvData.template) || CV_TEMPLATES[0];
      exportCVAsPDF(cvData, template);
    } finally {
      setIsExporting(null);
    }
  };

  const handleExportDocx = async () => {
    setIsExporting('docx');
    try {
      const template = CV_TEMPLATES.find(t => t.id === cvData.template) || CV_TEMPLATES[0];
      await exportCVAsDOCX(cvData, template);
    } catch (err) {
      console.error('DOCX export failed:', err);
    } finally {
      setIsExporting(null);
    }
  };

  // ----------------------------------------------------------------------------
  // RENDER
  // ----------------------------------------------------------------------------

  return (
    <div
      dir={isRtl ? 'rtl' : 'ltr'}
      style={{
        padding: '1.5rem',
        maxWidth: '1440px',
        margin: '0 auto',
        background: 'linear-gradient(180deg, #fefce8 0%, #ffffff 100%)',
        minHeight: '100vh',
      }}
    >
      {/* Header */}
      <div style={{ marginBottom: '1.5rem' }}>
        <h1
          style={{
            fontSize: '1.75rem',
            fontWeight: 700,
            color: '#0f172a',
            margin: 0,
            display: 'flex',
            alignItems: 'center',
            gap: '0.5rem',
          }}
        >
          <FileText size={28} className="text-amber-600" />
          {t.title}
        </h1>
        <p style={{ color: '#475569', marginTop: '0.25rem', fontSize: '0.95rem' }}>{t.subtitle}</p>
      </div>

      {/* Top toolbar */}
      <div
        style={{
          background: 'white',
          border: '1px solid #e2e8f0',
          borderRadius: '0.75rem',
          padding: '0.875rem 1.25rem',
          marginBottom: '1rem',
          display: 'flex',
          flexWrap: 'wrap',
          gap: '0.75rem',
          alignItems: 'center',
        }}
      >
        {/* Auto-generate */}
        <button
          onClick={handleAutoGenerate}
          disabled={isGenerating}
          style={{
            padding: '0.5rem 1rem',
            background: isGenerating ? '#fef3c7' : '#f59e0b',
            color: isGenerating ? '#92400e' : 'white',
            border: 'none',
            borderRadius: '0.5rem',
            cursor: isGenerating ? 'wait' : 'pointer',
            fontSize: '0.85rem',
            fontWeight: 600,
            display: 'inline-flex',
            alignItems: 'center',
            gap: '0.375rem',
          }}
        >
          {isGenerating ? <Loader size={14} className="animate-spin" /> : <Sparkles size={14} />}
          {isGenerating ? t.generating : t.generate}
        </button>

        {autoGenComplete && (
          <span style={{ display: 'inline-flex', alignItems: 'center', gap: '0.375rem', color: '#15803d', fontSize: '0.85rem', fontWeight: 500 }}>
            <CheckCircle2 size={14} />
            {t.autoGenDone}
          </span>
        )}

        <div style={{ flex: 1 }} />

        {/* Language */}
        <select
          value={cvData.language}
          onChange={e => setCvData({ ...cvData, language: e.target.value as CvLanguage })}
          style={{
            padding: '0.5rem 0.875rem',
            border: '1px solid #cbd5e1',
            borderRadius: '0.5rem',
            background: 'white',
            cursor: 'pointer',
            fontSize: '0.85rem',
          }}
        >
          <option value="en">English</option>
          <option value="ar">العربية</option>
          <option value="de">Deutsch</option>
        </select>

        {/* Color scheme */}
        <select
          value={cvData.colorScheme}
          onChange={e => setCvData({ ...cvData, colorScheme: e.target.value as CvColorScheme })}
          style={{
            padding: '0.5rem 0.875rem',
            border: '1px solid #cbd5e1',
            borderRadius: '0.5rem',
            background: 'white',
            cursor: 'pointer',
            fontSize: '0.85rem',
          }}
        >
          {Object.entries(CV_COLOR_SCHEMES).map(([key, val]) => (
            <option key={key} value={key}>
              {val.name[language]}
            </option>
          ))}
        </select>

        {/* Export buttons */}
        <button
          onClick={handleExportPdf}
          disabled={isExporting !== null}
          style={{
            padding: '0.5rem 0.875rem',
            background: isExporting === 'pdf' ? '#94a3b8' : '#dc2626',
            color: 'white',
            border: 'none',
            borderRadius: '0.5rem',
            cursor: isExporting !== null ? 'wait' : 'pointer',
            fontSize: '0.85rem',
            fontWeight: 600,
            display: 'inline-flex',
            alignItems: 'center',
            gap: '0.375rem',
          }}
        >
          {isExporting === 'pdf' ? <Loader size={14} className="animate-spin" /> : <Download size={14} />}
          {t.exportPdf}
        </button>

        <button
          onClick={handleExportDocx}
          disabled={isExporting !== null}
          style={{
            padding: '0.5rem 0.875rem',
            background: isExporting === 'docx' ? '#94a3b8' : '#2563eb',
            color: 'white',
            border: 'none',
            borderRadius: '0.5rem',
            cursor: isExporting !== null ? 'wait' : 'pointer',
            fontSize: '0.85rem',
            fontWeight: 600,
            display: 'inline-flex',
            alignItems: 'center',
            gap: '0.375rem',
          }}
        >
          {isExporting === 'docx' ? <Loader size={14} className="animate-spin" /> : <Download size={14} />}
          {t.exportDocx}
        </button>
      </div>

      {/* Templates gallery */}
      <div
        style={{
          background: 'white',
          border: '1px solid #e2e8f0',
          borderRadius: '0.75rem',
          padding: '1rem 1.25rem',
          marginBottom: '1rem',
        }}
      >
        <h3 style={{ fontSize: '0.95rem', fontWeight: 600, color: '#1e293b', margin: '0 0 0.75rem 0' }}>
          {t.templates} ({CV_TEMPLATES.length})
        </h3>
        <div style={{ display: 'flex', gap: '0.625rem', overflowX: 'auto', paddingBottom: '0.25rem' }}>
          {CV_TEMPLATES.map(template => (
            <button
              key={template.id}
              onClick={() => setCvData({ ...cvData, template: template.id })}
              style={{
                padding: '0.75rem 0.875rem',
                minWidth: '180px',
                background: cvData.template === template.id ? '#fef3c7' : 'white',
                border: `2px solid ${cvData.template === template.id ? '#f59e0b' : '#e2e8f0'}`,
                borderRadius: '0.5rem',
                cursor: 'pointer',
                textAlign: 'start',
                flexShrink: 0,
              }}
            >
              <div style={{ fontSize: '0.85rem', fontWeight: 600, color: '#0f172a' }}>
                {template.name[language]}
              </div>
              <div
                style={{
                  fontSize: '0.7rem',
                  color: '#64748b',
                  marginTop: '0.25rem',
                  display: '-webkit-box',
                  WebkitLineClamp: 2,
                  WebkitBoxOrient: 'vertical',
                  overflow: 'hidden',
                }}
              >
                {template.description[language]}
              </div>
            </button>
          ))}
        </div>
      </div>

      {/* Tabs */}
      <div style={{ display: 'flex', gap: '0.25rem', borderBottom: '2px solid #e2e8f0', marginBottom: '1rem' }}>
        {(['sections', 'preview'] as const).map(tab => (
          <button
            key={tab}
            onClick={() => setActiveTab(tab)}
            style={{
              padding: '0.75rem 1.25rem',
              background: 'transparent',
              border: 'none',
              borderBottom: activeTab === tab ? '3px solid #f59e0b' : '3px solid transparent',
              color: activeTab === tab ? '#b45309' : '#64748b',
              cursor: 'pointer',
              fontSize: '0.95rem',
              fontWeight: activeTab === tab ? 600 : 500,
              display: 'inline-flex',
              alignItems: 'center',
              gap: '0.5rem',
              marginBottom: '-2px',
            }}
          >
            {tab === 'sections' ? <Edit2 size={16} /> : <Eye size={16} />}
            {tab === 'sections' ? t.sections : t.preview}
          </button>
        ))}
      </div>

      {activeTab === 'sections' ? (
        <SectionsEditor
          language={language}
          cvData={cvData}
          setCvData={setCvData}
          t={t}
        />
      ) : (
        <PreviewView language={language} cvData={cvData} />
      )}
    </div>
  );
};

