export function buildExternalSearchUrl(
  source: ExternalMediaSourceConfig,
  query: string
): string {
  const trimmed = query.trim();
  if (!trimmed) return source.baseUrl;
  return source.searchUrlTemplate.replace('{query}', encodeURIComponent(trimmed));
}

export function getPlatformsForCategory(
  category: MediaCategory | 'all'
): ExternalMediaSourceConfig[] {
  if (category === 'all') return EXTERNAL_MEDIA_SOURCES;
  return EXTERNAL_MEDIA_SOURCES.filter(src => src.categories.includes(category));
}
