export function getDirectVideoUrl(media: VisualMedia): string {
  return media.externalSourceUrl || media.url;
}

export function getThumbnailWithFallback(media: VisualMedia): {
  url?: string;
  isGradient: boolean;
  gradient: string;
} {
  const gradient = FALLBACK_GRADIENTS[media.category] || FALLBACK_GRADIENTS["Other"];
  if (media.thumbnailUrl && media.thumbnailUrl.trim().length > 0) {
    return {
      url: media.thumbnailUrl,
      isGradient: false,
      gradient,
    };
  }
  return {
    isGradient: true,
    gradient,
  };
}

