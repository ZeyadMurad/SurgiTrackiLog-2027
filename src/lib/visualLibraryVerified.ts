export function extractYouTubeId(url: string): string | null {
  if (!url) return null;
  const patterns = [
    /(?:youtube\.com\/watch\?v=|youtu\.be\/|youtube\.com\/embed\/|youtube\.com\/shorts\/)([a-zA-Z0-9_-]{11})/,
    /^([a-zA-Z0-9_-]{11})$/,
  ];
  for (const p of patterns) {
    const m = url.match(p);
    if (m && m[1]) return m[1];
  }
  return null;
}

export function buildYouTubeSearchUrl(query: string): string {
  const clean = (query || 'surgical procedure').trim();
  return `https://www.youtube.com/results?search_query=${encodeURIComponent(clean + ' surgical procedure')}`;
}

